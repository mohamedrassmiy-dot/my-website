import fs from 'node:fs';import path from 'node:path';
const root=process.argv[2]||'release';
const appFile=path.join(root,'netlify/functions/app.mjs');
const siteJsFile=path.join(root,'assets/site.js');

function walk(dir){return fs.readdirSync(dir,{withFileTypes:true}).flatMap(e=>e.isDirectory()?walk(path.join(dir,e.name)):[path.join(dir,e.name)]);}

// Remove every public-facing client/admin login entry. /admin remains directly accessible only by URL.
for(const file of walk(root).filter(f=>f.endsWith('.html'))){
  if(file.includes(path.sep+'admin'+path.sep)) continue;
  let h=fs.readFileSync(file,'utf8');
  h=h.replace(/<a\b[^>]*href=["'][^"']*(?:\/admin(?:\/login)?|login\.html|dashboard\.html)[^"']*["'][^>]*>[\s\S]*?<\/a>/gi,'');
  h=h.replace(/<button\b[^>]*>[\s\S]*?(?:دخول العميل|Client Login)[\s\S]*?<\/button>/gi,'');
  fs.writeFileSync(file,h);
}

// Dynamic CMS pages must not advertise admin/client login either.
let app=fs.readFileSync(appFile,'utf8');
/* RASSMIY_ADMIN_SINGLE_ENTRY_V71
   /admin is the only admin entry point: anonymous GET/POST renders/processes login. */
app=app.replace("if(path==='/admin/login'){","if(path==='/admin' && !isAdmin(session)){");
app=app.replace("if(path==='/admin'){ if(!isAdmin(session))return saveAnd(redirect('/admin/login')); const user=currentUser(state,session);","if(path==='/admin'){ const user=currentUser(state,session);");
app=app.replaceAll("redirect('/admin/login')","redirect('/admin')");

app=app.replace(/<a\b[^>]*href=["']\/admin(?:\/login)?["'][^>]*>[\s\S]*?<\/a>/gi,'');
app=app.replace(/<a\b[^>]*href=["'][^"']*(?:login|dashboard)\.html[^"']*["'][^>]*>[\s\S]*?<\/a>/gi,'');
fs.writeFileSync(appFile,app);

// Runtime guard for menus generated by older markup or scripts.
let js=fs.readFileSync(siteJsFile,'utf8');
if(!js.includes('__RASSMIY_PUBLIC_AUTH_SCRUB_V70__')) js+=String.raw`
;(()=>{
  if(window.__RASSMIY_PUBLIC_AUTH_SCRUB_V70__)return;
  window.__RASSMIY_PUBLIC_AUTH_SCRUB_V70__=true;
  if(location.pathname.startsWith('/admin'))return;
  const scrub=()=>document.querySelectorAll('a[href],button').forEach(el=>{
    const href=(el.getAttribute?.('href')||'').toLowerCase();
    const txt=(el.textContent||'').trim().toLowerCase();
    if(/(^|\/)(admin(?:\/login)?|login\.html|dashboard\.html)(?:[?#/]|$)/.test(href)||
       txt==='دخول العميل'||txt==='client login'||txt==='admin'||txt==='دخول الإدارة') el.remove();
  });
  const run=()=>{scrub();new MutationObserver(scrub).observe(document.body,{childList:true,subtree:true});};
  document.readyState==='loading'?document.addEventListener('DOMContentLoaded',run):run();
})();
`;
fs.writeFileSync(siteJsFile,js);

// Explicit old-login redirects handled inside the function.
app=fs.readFileSync(appFile,'utf8');
const routeAnchor="if(path==='/api/health')";
if(app.includes(routeAnchor)&&!app.includes('RASSMIY_LEGACY_LOGIN_REDIRECT_V70')){
  app=app.replace(routeAnchor,`// RASSMIY_LEGACY_LOGIN_REDIRECT_V70
  if(['/ar/login.html','/en/login.html','/ar/dashboard.html','/en/dashboard.html','/admin/login'].includes(path))return redirect('/admin',301);
  `+routeAnchor);
}
fs.writeFileSync(appFile,app);

// Build-time proof used by QA.
fs.writeFileSync(path.join(root,'runtime-hotfix-v70.json'),JSON.stringify({
  version:'7.0',publicClientLoginRemoved:true,legacyLoginRedirect:'/admin',
  runtimeDependencyPolicy:'sanitize-html pinned for Netlify compatibility'
},null,2));
